package com.tiffintracker.util

import android.content.Context
import android.content.Intent
import android.net.Uri
import com.tiffintracker.data.db.Payment
import com.tiffintracker.data.repository.BillSummary

fun generateBillText(
    providerName: String,
    yearMonth: String,
    billSummary: BillSummary,
    payments: List<Payment>
): String = buildString {
    appendLine("═══════════════════════════")
    appendLine("  TIFFIN BILL - $yearMonth")
    appendLine("═══════════════════════════")
    appendLine("Provider: $providerName")
    appendLine()
    appendLine("── Meals ──")
    if (billSummary.breakfastCount > 0) {
        appendLine("Breakfast: ${billSummary.breakfastCount} × ${formatCurrency(billSummary.breakfastAmount / billSummary.breakfastCount)} = ${formatCurrency(billSummary.breakfastAmount)}")
    }
    if (billSummary.lunchCount > 0) {
        appendLine("Lunch:     ${billSummary.lunchCount} × ${formatCurrency(billSummary.lunchAmount / billSummary.lunchCount)} = ${formatCurrency(billSummary.lunchAmount)}")
    }
    if (billSummary.dinnerCount > 0) {
        appendLine("Dinner:    ${billSummary.dinnerCount} × ${formatCurrency(billSummary.dinnerAmount / billSummary.dinnerCount)} = ${formatCurrency(billSummary.dinnerAmount)}")
    }
    appendLine("───────────────────────────")
    appendLine("Total:     ${formatCurrency(billSummary.totalAmount)}")
    appendLine()

    if (payments.isNotEmpty()) {
        appendLine("── Payments ──")
        for (payment in payments) {
            appendLine("${payment.date}  ${formatCurrency(payment.amount)}  (${payment.mode})")
        }
        appendLine("───────────────────────────")
        appendLine("Total Paid: ${formatCurrency(billSummary.totalPaid)}")
    }

    appendLine()
    val balance = billSummary.balanceDue
    if (balance > 0) {
        appendLine("BALANCE DUE: ${formatCurrency(balance)}")
    } else if (balance < 0) {
        appendLine("ADVANCE: ${formatCurrency(-balance)}")
    } else {
        appendLine("FULLY PAID ✓")
    }
    appendLine("═══════════════════════════")
    appendLine("Generated by Tiffin Tracker")
}

fun shareBillViaWhatsApp(context: Context, phone: String, text: String) {
    val cleanPhone = phone.replace(Regex("[^0-9+]"), "")
    val url = "https://wa.me/$cleanPhone?text=${Uri.encode(text)}"
    val intent = Intent(Intent.ACTION_VIEW, Uri.parse(url)).apply {
        flags = Intent.FLAG_ACTIVITY_NEW_TASK
    }
    context.startActivity(intent)
}

fun shareText(context: Context, text: String) {
    val intent = Intent(Intent.ACTION_SEND).apply {
        type = "text/plain"
        putExtra(Intent.EXTRA_TEXT, text)
        flags = Intent.FLAG_ACTIVITY_NEW_TASK
    }
    context.startActivity(Intent.createChooser(intent, "Share Bill").apply {
        flags = Intent.FLAG_ACTIVITY_NEW_TASK
    })
}
